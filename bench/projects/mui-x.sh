# MUI X, the Node.js projects: the jsdom projects (packages/*, docs,
# test/x-license-compat) and the node projects. Without BROWSER=true, the root
# config lists no browser projects. Vitest 5.0.5 from the lockfile.
setup_mui_x() {
  local d=$R/mui-x
  clone $d https://github.com/mui/mui-x.git 467d8deb3b22263a78746f2be1b40e17af819ce3
  installed $d || install $d --frozen-lockfile
  config mui-x.vitest.bench.config.mts $d/vitest.bench.config.mts
  config mui-x.vitest.bench.shared.mts $d/vitest.bench.shared.mts
  # The root `test.pool` does not reach a project that is a separate config
  # file, so each jsdom and node project config gets a bench variant next to it.
  (cd $d && for f in packages/*/vitest.config.jsdom.mts docs/vitest.config.jsdom.mts \
      test/x-license-compat/vitest.config.jsdom.mts packages/*/vitest.config.node.mts; do
    dir=$(dirname "$f"); name=$(basename "$f")
    up=$(echo "$dir" | sed 's|[^/][^/]*|..|g')
    cat > "$dir/${name/vitest.config./vitest.bench.config.}" <<EOT
// Generated by bench/projects/mui-x.sh of vitest-pool-fastforks.
import base from './$name'
import { benchProject } from '$up/vitest.bench.shared.mts'

export default benchProject(base, import.meta.url)
EOT
  done)
}
proj_mui_x() {
  DIR=$R/mui-x
  VITEST_BIN=$DIR/node_modules/vitest/vitest.mjs
  ARGS=(--config vitest.bench.config.mts --configLoader runner)
  # BENCH_EXCLUDE (see vitest.bench.shared.mts), 10 files:
  # - materialVersion.test.tsx (9 packages) runs `pnpm config list --json`,
  #   which downloads pnpm and rewrites pnpm-lock.yaml. It times out with both pools.
  # - remendEsmBundle.test.ts runs `vite build` into node_modules.
  ENVS=(TZ=UTC NODE_ENV=test BROWSER=false
    'BENCH_EXCLUDE=**/src/tests/materialVersion.test.tsx,**/src/tests/packagingGuard/remendEsmBundle.test.ts')
  ENV_FILE=
  # The forks run with 4 CPUs takes about 21 minutes.
  TIMEOUT=3600
}
